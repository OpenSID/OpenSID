namespace App\Services\Acak\Sanitizers;

use App\Services\Acak\AcakContext;
use App\Services\Acak\AcakResult;
use App\Services\Acak\Contracts\Sanitizer;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;

/**
 * Setel ulang kredensial layanan mandiri (tweb_penduduk_mandiri): PIN ke default
 * uji "000000" dan hapus scan KTP/KK serta foto selfie.
 */
final class LayananMandiriSanitizer implements Sanitizer
{
    // bcrypt hash dari "000000" — PIN uji yang aman untuk database demo.
    private const PIN_DEMO = '$2y$10$92IXUNpkjO0rOQ5byMi.Ye4oKoEa3Ro9llC/.og/at2.uheWG/igi';

    public function label(): string
    {
        return 'Mereset kredensial layanan mandiri';
    }

    public function sanitize(AcakContext $context, AcakResult $result): void
    {
        if (! Schema::hasTable('tweb_penduduk_mandiri')) {
            return;
        }

        $affected = DB::table('tweb_penduduk_mandiri')->update([
            'pin'         => self::PIN_DEMO,
            'scan_ktp'    => null,
            'scan_kk'     => null,
            'foto_selfie' => null,
        ]);

        if ($affected > 0) {
            $result->markTable('tweb_penduduk_mandiri');
            $result->addRows($affected);
        }
    }
}
