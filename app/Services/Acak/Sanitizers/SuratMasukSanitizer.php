namespace App\Services\Acak\Sanitizers;

use App\Services\Acak\AcakContext;
use App\Services\Acak\AcakResult;
use App\Services\Acak\Contracts\Sanitizer;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;

/**
 * Buang rujukan berkas hasil pindai (`berkas_scan`) pada `surat_masuk` agar
 * dokumen ber-PII tidak lagi dirujuk dari database.
 */
final class SuratMasukSanitizer implements Sanitizer
{
    public function label(): string
    {
        return 'Membersihkan berkas surat masuk';
    }

    public function sanitize(AcakContext $context, AcakResult $result): void
    {
        if (! Schema::hasTable('surat_masuk')) {
            return;
        }

        $count = DB::table('surat_masuk')->whereNotNull('berkas_scan')->update(['berkas_scan' => null]);

        if ($count > 0) {
            $result->markTable('surat_masuk');
            $result->addRows($count);
        }
    }
}
