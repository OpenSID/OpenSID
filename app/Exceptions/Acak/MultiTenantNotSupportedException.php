namespace App\Exceptions\Acak;

use RuntimeException;

/**
 * Dilempar saat fitur acak dijalankan pada database multi-desa (multitenant).
 *
 * Acak adalah alat de-identifikasi untuk satu desa; pada database multitenant ia
 * akan mengubah data seluruh desa sekaligus — tidak pernah diinginkan. Guard ini
 * ada di {@see \App\Services\Acak\AcakService::run()} sebagai jaring pengaman
 * terakhir, sehingga berlaku untuk semua titik masuk (CLI maupun web).
 */
class MultiTenantNotSupportedException extends RuntimeException
{
    public const PESAN = 'Fitur acak data tidak tersedia untuk database multi-desa (multitenant).';

    public function __construct(string $message = self::PESAN)
    {
        parent::__construct($message);
    }
}
