namespace Modules\Kehadiran\Traits;

trait HasIndonesianDateFormat
{
    /**
     * Get Indonesian month name (shared utility method)
     *
     * @param int $month 1-12
     */
    protected function getBulanIndonesia(int $month): string
    {
        $bulanMap = [
            1  => 'Januari',
            2  => 'Februari',
            3  => 'Maret',
            4  => 'April',
            5  => 'Mei',
            6  => 'Juni',
            7  => 'Juli',
            8  => 'Agustus',
            9  => 'September',
            10 => 'Oktober',
            11 => 'November',
            12 => 'Desember',
        ];

        return $bulanMap[$month] ?? 'Bulan_' . $month;
    }

    /**
     * Get Indonesian day name (shared utility method)
     *
     * @param int $day 0-6 (0=Sunday, 6=Saturday)
     */
    protected function getHariIndonesia(int $day): string
    {
        $hariMap = [
            0 => 'Minggu',
            1 => 'Senin',
            2 => 'Selasa',
            3 => 'Rabu',
            4 => 'Kamis',
            5 => 'Jumat',
            6 => 'Sabtu',
        ];

        return $hariMap[$day] ?? 'Hari_' . $day;
    }
}
